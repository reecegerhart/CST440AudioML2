"""
quantize.py - Step 6 prep: shrink the trained model to int8 so it fits on the Arduino.

Needs models/speech_model.keras and data/representative_features.npy from train.py,
and DataSet_clean/ from prepare_data.py (for the accuracy check).

What it does
  * Full integer (int8) post-training quantization: weights AND activations become int8,
    and the input/output tensors are int8 too, which is what TensorFlow Lite Micro on the
    Arduino Nano 33 BLE Sense needs. The converter runs the 300 representative clips
    (50 per class) through the model to learn the range of every layer's values, and
    picks a scale + zero point for each one:   real_value = scale * (int8_value - zero_point)
  * Also makes a "dynamic range" model (int8 weights, float math) for comparison only.
    It is smaller than float but can't run on the microcontroller.
  * Tests float32, dynamic range and int8 on the same held-out test speakers.

Writes
  models/speech_model_int8.tflite     the model for the board
  models/speech_model_dynamic.tflite  comparison only
  models/model_data.h                 int8 model as a C array for the Arduino sketch
  models/quantization_results.txt     size / accuracy table for the report
  models/confusion_matrix_int8.png    test-set confusion matrix of the int8 model

Run:  python quantize.py
"""
import time
from pathlib import Path

import numpy as np
import tensorflow as tf

import features as F
from app import CSV_PATH, SpeechModel
from train import LABELS, plot_confusion, report_text

BASE = Path(__file__).resolve().parent
MODEL_DIR = BASE / "models"
KERAS_MODEL = MODEL_DIR / "speech_model.keras"
REP_DATA = BASE / "data" / "representative_features.npy"
FLOAT_MODEL = MODEL_DIR / "speech_model_float.tflite"
INT8_MODEL = MODEL_DIR / "speech_model_int8.tflite"
DYNAMIC_MODEL = MODEL_DIR / "speech_model_dynamic.tflite"
HEADER = MODEL_DIR / "model_data.h"
TARGET_ACCURACY = 95.0


# ----------------------------------------------------------------------------
# Quantize
# ----------------------------------------------------------------------------
def quantize_int8(model, rep):
    def representative_dataset():
        for sample in rep:                       # one clip at a time, shape (1, 49, 40, 1)
            yield [sample[np.newaxis].astype(np.float32)]

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = representative_dataset
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = converter.inference_output_type = tf.int8
    return converter.convert()


def quantize_dynamic(model):
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    return converter.convert()


def write_c_array(tflite_bytes, path):
    """Same idea as `xxd -i`, plus alignas(16) which TensorFlow Lite Micro needs."""
    q_in, q_out = tensor_quantization(tflite_bytes)
    hex_rows = [", ".join(f"0x{b:02x}" for b in tflite_bytes[i:i + 12])
                for i in range(0, len(tflite_bytes), 12)]
    path.write_text(
        "// Generated by quantize.py from models/speech_model_int8.tflite - don't edit by hand.\n"
        "// Input : int8 [1, 49, 40, 1] log-mel spectrogram (see models/features.json)\n"
        f"//         int8 = round(log_mel / {q_in[0]:.8f}) + ({q_in[1]})\n"
        "// Output: int8 [1, 6] scores in this order: " + ", ".join(LABELS) + "\n"
        f"//         probability = (int8 - ({q_out[1]})) * {q_out[0]:.8f}\n"
        "#ifndef SPEECH_MODEL_DATA_H\n#define SPEECH_MODEL_DATA_H\n\n"
        f"const float g_input_scale = {q_in[0]:.8f}f;\nconst int g_input_zero_point = {q_in[1]};\n"
        f"const float g_output_scale = {q_out[0]:.8f}f;\nconst int g_output_zero_point = {q_out[1]};\n"
        f"const char* const g_labels[] = {{{', '.join(f'{chr(34)}{n}{chr(34)}' for n in LABELS)}}};\n"
        f"const int g_num_labels = {len(LABELS)};\n\n"
        "alignas(16) const unsigned char g_model[] = {\n  "
        + ",\n  ".join(hex_rows)
        + f"\n}};\nconst unsigned int g_model_len = {len(tflite_bytes)};\n\n#endif\n")


def tensor_quantization(tflite_bytes):
    interp = tf.lite.Interpreter(model_content=tflite_bytes)
    return (interp.get_input_details()[0]["quantization"],
            interp.get_output_details()[0]["quantization"])


# ----------------------------------------------------------------------------
# Compare on the held-out test speakers
# ----------------------------------------------------------------------------
def load_test_set():
    import csv
    with CSV_PATH.open(newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["split"] == "test"]
    waves = np.stack([F.fix_length(F.load_wav(BASE / r["filename"])) for r in rows])
    return F.features(waves), np.array([LABELS.index(r["label"]) for r in rows])


def evaluate(path, X, y):
    model = SpeechModel(path)
    start = time.perf_counter()
    probs = model.probabilities(X)
    ms = (time.perf_counter() - start) / len(X) * 1000
    pred = probs.argmax(axis=1)
    kind = "int8 weights" if path == DYNAMIC_MODEL else model.kind   # float in/out, int8 weights
    return {"name": path.name, "kind": kind, "kb": model.size_bytes / 1024,
            "acc": np.mean(pred == y) * 100, "ms": ms, "pred": pred}


def main():
    if not (BASE / "DataSet_clean").exists():
        raise SystemExit("DataSet_clean/ is missing - run  python prepare_data.py  first")
    model = tf.keras.models.load_model(KERAS_MODEL)
    rep = np.load(REP_DATA)
    print(f"Representative dataset: {rep.shape[0]} clips, "
          f"values {rep.min():.2f} to {rep.max():.2f}")

    INT8_MODEL.write_bytes(quantize_int8(model, rep))
    DYNAMIC_MODEL.write_bytes(quantize_dynamic(model))
    write_c_array(INT8_MODEL.read_bytes(), HEADER)

    q_in, q_out = tensor_quantization(INT8_MODEL.read_bytes())
    print(f"int8 input : scale {q_in[0]:.6f}, zero point {q_in[1]}")
    print(f"int8 output: scale {q_out[0]:.6f}, zero point {q_out[1]}")

    print("Loading test set...")
    X, y = load_test_set()
    results = [evaluate(p, X, y) for p in (FLOAT_MODEL, DYNAMIC_MODEL, INT8_MODEL)]
    base, int8 = results[0], results[-1]
    agree = np.mean(base["pred"] == int8["pred"]) * 100

    lines = ["=== Quantization results (test set: speakers never seen in training) ===",
             f"{'model':<30}{'type':<16}{'size KB':>9}{'accuracy':>10}{'ms/clip':>9}"]
    for r in results:
        lines.append(f"{r['name']:<30}{r['kind']:<16}{r['kb']:>9.1f}{r['acc']:>9.2f}%{r['ms']:>9.3f}")
    lines += ["",
              f"int8 vs float32: {base['kb'] / int8['kb']:.1f}x smaller, accuracy change "
              f"{int8['acc'] - base['acc']:+.2f} points",
              f"int8 and float32 give the same answer on {agree:.2f}% of clips",
              f"Target {TARGET_ACCURACY:.0f}%: {'MET' if int8['acc'] >= TARGET_ACCURACY else 'NOT MET'}",
              f"int8 input : scale {q_in[0]:.8f}, zero point {q_in[1]}",
              f"int8 output: scale {q_out[0]:.8f}, zero point {q_out[1]}",
              "", report_text(y, int8["pred"], "=== int8 model, per class ===")]
    text = "\n".join(lines)
    print("\n" + text)
    (MODEL_DIR / "quantization_results.txt").write_text(text + "\n")
    plot_confusion(y, int8["pred"], MODEL_DIR / "confusion_matrix_int8.png")
    print(f"\nSaved {INT8_MODEL.name}, {DYNAMIC_MODEL.name}, {HEADER.name}, "
          "quantization_results.txt, confusion_matrix_int8.png")


if __name__ == "__main__":
    main()
