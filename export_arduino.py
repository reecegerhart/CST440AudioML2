"""
export_arduino.py - Step 6: get the Arduino sketch ready, and check it on the PC first.

Needs models/model_data.h from quantize.py, and DataSet_clean/ from prepare_data.py.

1. Writes  arduino/speech_commands/mel_weights.h  (the mel filter weights from features.py)
   and copies  models/model_data.h  into the sketch folder.
2. Check (skip with --no-check): compiles the sketch's feature code
   (arduino/speech_commands/audio_features.cpp) for the PC, runs it on every test clip,
   and compares it with features.py. Then runs the int8 model on the C++ features,
   quantized exactly like the sketch does, to show the accuracy the board should get.
   The compiler comes from:  pip install ziglang

Run:  python export_arduino.py
"""
import argparse
import shutil
import subprocess
import sys
import wave
from pathlib import Path

import numpy as np
import tensorflow as tf

import features as F
from app import CSV_PATH
from train import LABELS

BASE = Path(__file__).resolve().parent
SKETCH = BASE / "arduino" / "speech_commands"
HOST_TEST = BASE / "arduino" / "host_test" / "feature_test.cpp"
BUILD = BASE / "arduino" / "build"
INT8_MODEL = BASE / "models" / "speech_model_int8.tflite"


def write_mel_weights(path):
    """Only the non-zero part of each mel band, so the board does ~500 multiplies, not 10,280."""
    mel = F.MEL_MATRIX.numpy()                            # (257 FFT bins, 40 mel bands)
    starts, counts, offsets, weights = [], [], [], []
    for m in range(F.NUM_MEL_BINS):
        nz = np.nonzero(mel[:, m])[0]
        first, last = (int(nz[0]), int(nz[-1])) if len(nz) else (0, -1)
        starts.append(first); counts.append(last - first + 1); offsets.append(len(weights))
        weights += mel[first:last + 1, m].tolist()
    fmt = lambda vals, f: ",\n  ".join(", ".join(f(v) for v in vals[i:i + 8])
                                       for i in range(0, len(vals), 8))
    path.write_text(
        "// Generated by export_arduino.py from features.py - don't edit by hand.\n"
        f"// Mel filters: {F.NUM_MEL_BINS} bands, {F.LOWER_HZ:g}-{F.UPPER_HZ:g} Hz, "
        f"{F.FFT_LENGTH // 2 + 1} FFT bins. Band m uses FFT bins\n"
        "// g_mel_start[m] .. g_mel_start[m] + g_mel_count[m] - 1, "
        "with weights starting at g_mel_weights[g_mel_offset[m]].\n"
        "#ifndef MEL_WEIGHTS_H\n#define MEL_WEIGHTS_H\n\n"
        f"const short g_mel_start[{F.NUM_MEL_BINS}] = {{\n  {fmt(starts, str)}\n}};\n"
        f"const short g_mel_count[{F.NUM_MEL_BINS}] = {{\n  {fmt(counts, str)}\n}};\n"
        f"const short g_mel_offset[{F.NUM_MEL_BINS}] = {{\n  {fmt(offsets, str)}\n}};\n"
        f"const float g_mel_weights[{len(weights)}] = {{\n  {fmt(weights, lambda v: f'{v:.9g}f')}\n}};\n"
        "\n#endif\n")
    return len(weights)


def read_int16(path):
    with wave.open(str(path)) as w:
        return np.frombuffer(w.readframes(w.getnframes()), np.int16)


def check():
    import csv
    if not (BASE / "DataSet_clean").exists():
        raise SystemExit("DataSet_clean/ is missing - run  python prepare_data.py  first")
    BUILD.mkdir(exist_ok=True)
    exe = BUILD / "feature_test.exe"
    print("Compiling the sketch's feature code for the PC...")
    subprocess.run([sys.executable, "-m", "ziglang", "c++", "-O2", "-w", "-o", str(exe),
                    str(HOST_TEST), str(SKETCH / "audio_features.cpp"), "-I", str(SKETCH)],
                   check=True)

    with CSV_PATH.open(newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["split"] == "test"]
    clips = np.stack([F.fix_length(read_int16(BASE / r["filename"]).astype(np.float32))
                      for r in rows]).astype(np.int16)
    y = np.array([LABELS.index(r["label"]) for r in rows])
    clips.tofile(BUILD / "clips.raw")
    subprocess.run([str(exe), str(BUILD / "clips.raw"), str(BUILD / "features.raw")], check=True)
    cpp = np.fromfile(BUILD / "features.raw", np.float32).reshape(len(rows), *F.INPUT_SHAPE)
    py = F.features(clips.astype(np.float32) / 32768.0)

    diff = np.abs(cpp - py)
    print(f"\nC++ vs features.py on {len(rows)} test clips:")
    print(f"  largest difference {diff.max():.5f}, average {diff.mean():.7f} "
          f"(log-mel values range {py.min():.1f} to {py.max():.1f})")

    interp = tf.lite.Interpreter(model_path=str(INT8_MODEL))
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    scale, zero = inp["quantization"]

    def quantize(x):                       # lroundf() in the sketch rounds .5 away from 0
        q = np.sign(x / scale) * np.floor(np.abs(x / scale) + 0.5) + zero
        return np.clip(q, -128, 127).astype(np.int8)

    q_cpp, q_py = quantize(cpp), quantize(py)
    print(f"  int8 inputs identical: {np.mean(q_cpp == q_py) * 100:.3f}% of values, "
          f"max difference {np.abs(q_cpp.astype(int) - q_py).max()} step(s)")
    results = {}
    for name, q in (("features.py", q_py), ("Arduino C++", q_cpp)):
        pred = []
        for x in q:
            interp.set_tensor(inp["index"], x[np.newaxis])
            interp.invoke()
            pred.append(interp.get_tensor(out["index"])[0].argmax())
        results[name] = np.array(pred)
        print(f"  int8 model accuracy with {name} features: "
              f"{np.mean(results[name] == y) * 100:.2f}%")
    print(f"  same answer on {np.mean(results['features.py'] == results['Arduino C++']) * 100:.2f}% "
          "of clips")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--no-check", action="store_true", help="only write the header files")
    a = p.parse_args()
    n = write_mel_weights(SKETCH / "mel_weights.h")
    shutil.copy(BASE / "models" / "model_data.h", SKETCH / "model_data.h")
    print(f"Wrote mel_weights.h ({n} weights) and copied model_data.h into {SKETCH.relative_to(BASE)}")
    if not a.no_check:
        check()


if __name__ == "__main__":
    main()
